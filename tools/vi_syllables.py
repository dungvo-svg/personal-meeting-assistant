"""Which words of a transcript are valid Vietnamese syllables. A signal about a reading, not proof of meaning.

The syllable list is generated by rule (onset + rhyme + tone, with the c/k/q, g/gh, ng/ngh spelling rules and the rule that a
stop coda p/t/c/ch only takes the rising or the heavy tone); no word list is copied from anywhere. It over-generates a little
(rare rhymes that no word uses) and never needs updating for new words. Change the rules, bump VERSION: the version is stored
next to every score so scores of different versions are never compared.

share(text) returns the numerator and the denominator, never a bare ratio: tokens that are numbers, all-capital abbreviations,
and capitalised words in the middle of a sentence that are not syllables (names) stay out of the
denominator. Lao and Thai script tokens stay IN the denominator, as non-syllables. Fewer than MIN_TOKENS tokens: share is None.
"""
import re
import unicodedata

VERSION = 'vi-syl-rule-1'
MIN_TOKENS = 3

TONES = {'̀': 'huyen', '́': 'sac', '̉': 'hoi', '̃': 'nga', '̣': 'nang'}
STOP_CODAS = ('p', 't', 'c', 'ch')
# Rhymes by vowel group, with the codas each may take ('' = open).
_RHYMES = {
    'a': ('', 'c', 'ch', 'm', 'n', 'ng', 'nh', 'p', 't'), 'ă': ('c', 'm', 'n', 'ng', 'p', 't'), 'â': ('c', 'm', 'n', 'ng', 'p', 't'),
    'e': ('', 'c', 'm', 'n', 'ng', 'p', 't'), 'ê': ('', 'ch', 'm', 'n', 'nh', 'p', 't'), 'i': ('', 'ch', 'm', 'n', 'nh', 'p', 't'),
    'y': ('',), 'o': ('', 'c', 'm', 'n', 'ng', 'p', 't'), 'ô': ('', 'c', 'm', 'n', 'ng', 'p', 't'), 'ơ': ('', 'm', 'n', 'p', 't'),
    'u': ('', 'c', 'm', 'n', 'ng', 'p', 't'), 'ư': ('', 'c', 'ng', 't'), 'oo': ('c', 'ng'),
    'ai': ('',), 'ao': ('',), 'au': ('',), 'âu': ('',), 'ay': ('',), 'ây': ('',), 'eo': ('',), 'êu': ('',), 'iu': ('',), 'oi': ('',), 'ôi': ('',),
    'ơi': ('',), 'ui': ('',), 'ưi': ('',), 'ưu': ('',), 'oe': ('', 'n', 't'), 'ia': ('',), 'ua': ('',), 'ưa': ('',), 'uơ': ('',), 'oeo': ('',),
    'iê': ('c', 'm', 'n', 'ng', 'p', 't', 'u'), 'yê': ('m', 'n', 'ng', 't', 'u'), 'uô': ('', 'c', 'm', 'n', 'ng', 't', 'i'), 'ươ': ('c', 'm', 'n', 'ng', 'p', 't', 'i', 'u'),
    'oa': ('', 'c', 'ch', 'm', 'n', 'ng', 'nh', 'p', 't', 'i', 'y'), 'oă': ('c', 'm', 'n', 'ng', 't'), 'uâ': ('n', 'ng', 't'), 'uê': ('', 'ch', 'n', 'nh'),
    'uy': ('', 'ch', 'n', 'nh', 't', 'p'), 'uyê': ('n', 't'), 'uya': ('',), 'uyu': ('',), 'uây': ('',),
}
_ONSETS = ('', 'b', 'c', 'ch', 'd', 'đ', 'g', 'gh', 'gi', 'h', 'k', 'kh', 'l', 'm', 'n', 'ng', 'ngh', 'nh', 'p', 'ph', 'qu', 'r', 's', 't', 'th', 'tr', 'v', 'x')
_FRONT = ('e', 'ê', 'i', 'y', 'iê', 'yê')


_SECOND = ('oa', 'oe', 'uy', 'oai', 'oay', 'oeo', 'uyu', 'uya', 'oo')
_NO_MARK = ('',)
_ALL_MARKS = ('', '̀', '̉', '̃', '́', '̣')
_STOP_MARKS = ('́', '̣')


def _spell(onset, vowels, coda, mark):
    # The written syllable with the tone mark on the right vowel (modern rule), composed to NFC: the last letter with a diacritic
    # (ă â ê ô ơ ư: ươ -> ơ, uyê -> ê); else a lone vowel; else the second letter of oa/oe/uy; else the last vowel when a coda follows,
    # the first of an open diphthong.
    letters = list(vowels)
    marked = [i for i, ch in enumerate(letters) if ch in 'ăâêôơư']
    if marked:
        target = marked[-1]
    elif len(letters) == 1:
        target = 0
    elif vowels in _SECOND:
        target = 1
    else:
        target = len(letters) - 1 if coda else 0
    if mark:
        letters[target] = unicodedata.normalize('NFC', letters[target] + mark)
    return unicodedata.normalize('NFC', onset + ''.join(letters) + coda)


def _ok_spelling(onset, vowels):
    front = vowels[0] in 'eêiy' or vowels in ('iê', 'yê')
    if onset == 'k':
        return front
    if onset == 'c':
        return not front
    if onset == 'gh':
        return front
    if onset == 'g':
        return not front
    if onset == 'ngh':
        return front
    if onset == 'ng':
        return not front
    if onset == 'qu':
        return vowels[0] not in 'uo' and vowels not in ('oa', 'oă', 'oe', 'oeo', 'oo', 'uâ', 'uê', 'uy', 'uyê', 'uya', 'uyu', 'uây', 'uô', 'uơ', 'ua')
    if onset == '' and vowels in ('iê',):
        return False  # written yê without an onset
    if onset == '' and vowels in ('uy',):
        return True
    return True


def generate():
    # The full set of toned, written syllables.
    out = set()
    for onset in _ONSETS:
        for vowels, codas in _RHYMES.items():
            if not _ok_spelling(onset, vowels):
                continue
            for coda in codas:
                for mark in (_STOP_MARKS if coda in STOP_CODAS else _ALL_MARKS):
                    out.add(_spell(onset, vowels, coda, mark))
                    if mark and not coda and vowels in ('oa', 'oe', 'uy'):
                        out.add(unicodedata.normalize('NFC', onset + vowels[0] + mark + vowels[1]))  # old spelling: hòa, qúy
    # Zero onset: yê is the spelling (yên, yêu); "gì" is g + i with the i written once.
    for coda in ('m', 'n', 'ng', 't', 'u'):
        for mark in (_STOP_MARKS if coda in STOP_CODAS else _ALL_MARKS):
            out.add(_spell('', 'yê', coda, mark))
    for mark in _ALL_MARKS:
        out.add(_spell('g', 'i', '', mark))
    return frozenset(out)


SYLLABLES = generate()
# A token: letters (any script) with optional combining marks, or digits. Hyphen and apostrophe split tokens.
_TOKEN = re.compile(r"[^\W_]+", re.UNICODE)


def _strip_tone_lower(token):
    return unicodedata.normalize('NFC', token.lower())


def is_syllable(token):
    return _strip_tone_lower(token) in SYLLABLES


def _latin(token):
    return all(ch.isascii() and ch.isalpha() or unicodedata.name(ch, '').startswith(('LATIN',)) for ch in token)


def share(text):
    """Returns {'viSyllables': n, 'viTokens': d, 'viSyllableShare': n/d or None, 'viSyllableVersion': VERSION}."""
    text = unicodedata.normalize('NFC', text or '')
    numerator = denominator = 0
    for match in _TOKEN.finditer(text):
        token = match.group(0)
        start = match.start()
        before = text[:start].rstrip()
        sentence_start = not before or before[-1] in '.!?…\n'
        if any(ch.isdigit() for ch in token):
            continue
        valid = is_syllable(token)
        if valid:
            numerator += 1
            denominator += 1
            continue
        if len(token) >= 2 and token.isupper() and _latin(token):
            continue  # abbreviation (SBM, OKR)
        if token[:1].isupper() and not sentence_start and _latin(token):
            continue  # a name
        denominator += 1
    ratio = round(numerator / denominator, 3) if denominator >= MIN_TOKENS else None
    return {'viSyllables': numerator, 'viTokens': denominator, 'viSyllableShare': ratio, 'viSyllableVersion': VERSION}
